// Writes the compiled ABIs into @cairn/core as typed `as const` arrays, so the CLI,
// attester and indexer share one ABI without depending on the Hardhat toolchain.
// Run after `hardhat compile`; a parity test fails if the committed copy drifts.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const abiOf = (name) =>
  JSON.parse(readFileSync(here(`../artifacts/contracts/${name}.sol/${name}.json`), "utf8")).abi;

const out = `// GENERATED by packages/contracts/scripts/export-abi.mjs — do not edit by hand.
export const attestationRegistryAbi = ${JSON.stringify(abiOf("AttestationRegistry"), null, 2)} as const;

export const quorumPolicyAbi = ${JSON.stringify(abiOf("QuorumPolicy"), null, 2)} as const;
`;
writeFileSync(here("../../core/src/abi.ts"), out);
console.log("wrote packages/core/src/abi.ts");
